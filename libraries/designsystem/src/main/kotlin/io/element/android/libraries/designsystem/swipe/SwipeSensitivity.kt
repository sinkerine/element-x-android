package io.element.android.libraries.designsystem.swipe

import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.ui.platform.LocalViewConfiguration
import androidx.compose.ui.platform.ViewConfiguration

// The app drawer must wait at least as long as timeline reply gestures before claiming a drag.
const val HORIZONTAL_SWIPE_TOUCH_SLOP_MULTIPLIER = 3f

/** Multiplies touch slop for [content], leaving the other view configuration values unchanged. */
@Composable
fun SwipeSensitivity(
    sensitivityFactor: Float,
    content: @Composable () -> Unit,
) {
    val current = LocalViewConfiguration.current
    CompositionLocalProvider(
        LocalViewConfiguration provides object : ViewConfiguration by current {
            override val touchSlop: Float
                get() = current.touchSlop * sensitivityFactor
        }
    ) {
        content()
    }
}
